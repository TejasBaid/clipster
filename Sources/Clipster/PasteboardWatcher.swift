import AppKit
import ClipsterCore

/// Polls the general pasteboard's change count (the only reliable signal macOS
/// offers) and records new text into the store. Reading `changeCount` is a
/// cheap integer fetch, so a 250 ms poll costs effectively nothing.
@MainActor
final class PasteboardWatcher {
    private let store: ClipStore
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// nspasteboard.org markers that password managers and similar apps set
    /// to ask clipboard managers not to record an item.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.05
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Also called directly when the panel opens so a copy made a few ms
    /// earlier is already at the top.
    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = pasteboard.types ?? []
        guard Self.ignoredTypes.isDisjoint(with: types),
              let text = pasteboard.string(forType: .string) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        store.add(text, sourceApp: app?.localizedName, sourceBundleID: app?.bundleIdentifier)
    }
}
